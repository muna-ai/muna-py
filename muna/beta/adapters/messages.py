StopReason = Literal[
    "end_turn",
    "max_tokens",
    "stop_sequence",
    "tool_use",
    "pause_turn",
    "refusal"
]

class TextBlock(BaseModel):
    """
    Text content block.
    """
    type: Literal["text"] = Field(default="text", init=False)
    text: str = Field(description="Response text.")

class ThinkingBlock(BaseModel):
    """
    Thinking content block.
    """
    type: Literal["thinking"] = Field(default="thinking", init=False)
    thinking: str = Field(description="Reasoning contents preceding the final answer.")
    signature: str = Field(default="", description="Signature verifying the thinking block. Always empty for Muna predictions.")

class ToolUseBlock(BaseModel):
    """
    A tool invocation, whose input is accumulated from JSON deltas.
    """
    type: Literal["tool_use"] = Field(default="tool_use", init=False)
    id: str
    name: str
    input: dict[str, object]

ContentBlock = Annotated[
    TextBlock   |
    ThinkingBlock |
    ToolUseBlock,
    Field(discriminator="type")
]

class Message(BaseModel):
    """
    Message.
    """
    id: str = Field(description="Unique object identifier.")
    type: Literal["message"] = Field(default="message", init=False)
    role: Literal["assistant"] = Field(default="assistant", init=False)
    content: list[ContentBlock] = Field(description="Content generated by the model.")
    model: str = Field(description="The model that will complete your prompt.")
    stop_reason: StopReason | None = Field(description="Reason that we stopped.")
    stop_sequence: str | None = Field(default=None, description="Which custom stop sequence was generated, if any.")
    usage: Usage = Field(description="Billing and rate-limit usage.")

class Usage(BaseModel):
    """
    Billing usage.
    """
    input_tokens: int | None = Field(default=None, description="Number of input tokens which were used, excluding cached tokens.")
    output_tokens: int = Field(description="Number of output tokens which were used.")
    cache_creation_input_tokens: int | None = Field(default=None, description="Number of input tokens used to create the cache entry.")
    cache_read_input_tokens: int | None = Field(default=None, description="Number of input tokens read from the cache.")

class TextDelta(BaseModel):
    """
    Text content delta.
    """
    type: Literal["text_delta"] = Field(default="text_delta", init=False)
    text: str = Field(description="Text fragment.")

class ThinkingDelta(BaseModel):
    """
    Thinking content delta.
    """
    type: Literal["thinking_delta"] = Field(default="thinking_delta", init=False)
    thinking: str = Field(description="Reasoning text fragment.")

class InputJSONDelta(BaseModel):
    """
    A fragment of a tool invocation's JSON input.
    """
    type: Literal["input_json_delta"] = Field(default="input_json_delta", init=False)
    partial_json: str

class RawMessageStartEvent(BaseModel):
    """
    Message start event.
    """
    type: Literal["message_start"] = Field(default="message_start", init=False)
    message: Message = Field(description="Message with empty content.")

class RawContentBlockStartEvent(BaseModel):
    """
    Content block start event.
    """
    type: Literal["content_block_start"] = Field(default="content_block_start", init=False)
    index: int = Field(description="Content block index in the message.")
    content_block: ContentBlock = Field(description="Content block with empty contents.")

class RawContentBlockDeltaEvent(BaseModel):
    """
    Content block delta event.
    """
    type: Literal["content_block_delta"] = Field(default="content_block_delta", init=False)
    index: int = Field(description="Content block index in the message.")
    delta: Annotated[TextDelta | ThinkingDelta | InputJSONDelta, Field(discriminator="type")]

class RawContentBlockStopEvent(BaseModel):
    """
    Content block stop event.
    """
    type: Literal["content_block_stop"] = Field(default="content_block_stop", init=False)
    index: int = Field(description="Content block index in the message.")

class RawMessageDeltaEvent(BaseModel):
    """
    Message delta event.
    """
    class MessageDelta(BaseModel):
        stop_reason: StopReason | None = Field(default=None, description="Reason that we stopped.")
        stop_sequence: str | None = Field(default=None, description="Which custom stop sequence was generated, if any.")
    type: Literal["message_delta"] = Field(default="message_delta", init=False)
    delta: MessageDelta = Field(description="Changes to the top-level message.")
    usage: Usage = Field(description="Cumulative billing and rate-limit usage.")

class RawMessageStopEvent(BaseModel):
    """
    Message stop event.
    """
    type: Literal["message_stop"] = Field(default="message_stop", init=False)

RawMessageStreamEvent = Annotated[
    RawMessageStartEvent        |
    RawContentBlockStartEvent   |
    RawContentBlockDeltaEvent   |
    RawContentBlockStopEvent    |
    RawMessageDeltaEvent        |
    RawMessageStopEvent,
    Field(discriminator="type")
]

class _TextBlockParamDict(TypedDict):
    type: Literal["text"]
    text: str

class _MessageParamDict(TypedDict):
    role: Literal["user", "assistant"]
    content: str | list[
        _TextBlockParamDict | _ImageBlockParamDict | _ToolUseBlockParamDict |
        _ToolResultBlockParamDict | _ThinkingBlockParamDict
    ]

class _ImageBlockParamDict(TypedDict):
    type: Literal["image"]
    source: _Base64ImageSourceDict | _URLImageSourceDict

class _Base64ImageSourceDict(TypedDict):
    type: Literal["base64"]
    media_type: str
    data: str

class _URLImageSourceDict(TypedDict):
    type: Literal["url"]
    url: str

class _ToolUseBlockParamDict(TypedDict):
    type: Literal["tool_use"]
    id: str
    name: str
    input: dict[str, object]

class _ToolResultBlockParamDict(TypedDict):
    type: Literal["tool_result"]
    tool_use_id: str
    content: str | list[_TextBlockParamDict | _ImageBlockParamDict]
    is_error: NotRequired[bool]

class _ThinkingBlockParamDict(TypedDict):
    type: Literal["thinking"]
    thinking: str
    signature: NotRequired[str]

class ToolParam(TypedDict):
    name: str
    description: NotRequired[str]
    input_schema: dict[str, object]

class AnthropicMessagesOptions(BaseModel, **ConfigDict(extra="forbid", frozen=True)):
    """
    Anthropic messages options.
    """

class AnthropicMessagesAdapter(Adapter[Iterable[Prediction], AnthropicMessagesOptions, Iterator[RawMessageStreamEvent]]):
    """
    Prepare Anthropic inputs and lazily adapt prediction chunks into events.
    """
    kind: Literal["anthropic.messages.create"] = Field("anthropic.messages.create", init=False)
    messages: Parameter
    output: int
    max_tokens: Parameter | None = None
    stop_sequences: Parameter | None = None
    temperature: Parameter | None = None
    top_k: Parameter | None = None
    top_p: Parameter | None = None
    tools: Parameter | None = None
    images: Parameter | None = None

    @classmethod
    def from_signature(cls, signature: Signature) -> AnthropicMessagesAdapter | None:
        """
        Create an Anthropic messages adapter from a predictor signature.
        """
        signature = signature.model_copy(deep=True)
        # Messages parameter
        _, messages = get_parameter(
            signature.inputs,
            dtype=Dtype.list,
            denotation="openai.chat.completions.messages"
        )
        if messages is None:
            return None
        # Maximum output tokens
        _, max_tokens = get_parameter(
            signature.inputs,
            dtype=INTEGERS,
            denotation="openai.chat.completions.max_output_tokens"
        )
        # Stop sequences
        _, stop_sequences = get_parameter(
            signature.inputs,
            dtype=Dtype.list,
            denotation="openai.chat.completions.stop"
        )
        # Temperature
        _, temperature = get_parameter(
            signature.inputs,
            dtype=FLOATS,
            denotation="openai.chat.completions.temperature"
        )
        # Top K
        _, top_k = get_parameter(
            signature.inputs,
            dtype=INTEGERS,
            denotation="anthropic.messages.top_k"
        )
        # Top P
        _, top_p = get_parameter(
            signature.inputs,
            dtype=FLOATS,
            denotation="openai.chat.completions.top_p"
        )
        # Tools parameter
        _, tools = get_parameter(
            signature.inputs,
            dtype=Dtype.list,
            denotation="openai.chat.completions.tools"
        )
        # Images parameter
        _, images = get_parameter(
            signature.inputs,
            dtype=Dtype.image_list,
            denotation="openai.chat.completions.images"
        )
        # Validate inputs
        if not validate_inputs(signature, [
            messages,
            max_tokens,
            stop_sequences,
            temperature,
            top_k,
            top_p,
            tools,
            images
        ]):
            return None
        # Completion chunk output
        output, completion = get_parameter(signature.outputs, dtype=Dtype.dict)
        if completion is None or (completion.value_schema or {}).get("title") != "ChatCompletionChunk":
            return None
        # Return
        return cls(
            messages=messages,
            output=output,
            max_tokens=max_tokens,
            stop_sequences=stop_sequences,
            temperature=temperature,
            top_k=top_k,
            top_p=top_p,
            tools=tools,
            images=images
        )

    def inputs(
        self,
        *,
        max_tokens: int,
        messages: list[_MessageParamDict],
        system: str | list[_TextBlockParamDict] | None = None,
        stop_sequences: list[str] | None = None,
        temperature: float | None = None,
        top_k: int | None = None,
        top_p: float | None = None,
        tools: list[ToolParam] | None = None
    ) -> dict[str, Value]:
        """
        Create prediction inputs from a messages request.
        """
        inputs = self._conversation(messages, system)
        if self.max_tokens is not None:
            inputs[self.max_tokens.name] = max_tokens
        if self.stop_sequences is not None and stop_sequences is not None:
            inputs[self.stop_sequences.name] = stop_sequences
        if self.temperature is not None and temperature is not None:
            inputs[self.temperature.name] = temperature
        if self.top_k is not None and top_k is not None:
            inputs[self.top_k.name] = top_k
        if self.top_p is not None and top_p is not None:
            inputs[self.top_p.name] = top_p
        if tools is not None:
            if self.tools is None:
                raise ValueError("This predictor does not support tools")
            inputs[self.tools.name] = [
                {
                    "type": "function",
                    "function": {
                        "name": tool["name"],
                        "parameters": tool["input_schema"],
                        **({ "description": tool["description"] } if "description" in tool else {})
                    }
                }
                for tool in tools
            ]
        return inputs

    def adapt(
        self,
        predictions: Iterable[Prediction],
        options: AnthropicMessagesOptions | None = None
    ) -> Iterator[RawMessageStreamEvent]:
        source = iter(predictions)
        def chunks() -> Iterator[ChatCompletionChunk]:
            for prediction in source:
                yield ChatCompletionChunk.model_validate(decode(result(prediction, self.output), Dtype.dict))
        try:
            yield from message_events(chunks())
        finally:
            close = getattr(source, "close", None)
            if close is not None:
                close()

    def _conversation(
        self,
        messages: list[_MessageParamDict],
        system: str | list[_TextBlockParamDict] | None
    ) -> dict[str, Value]:
        if not messages:
            raise ValueError("messages must contain at least one message")
        conversation = []
        images = []
        if system is not None:
            conversation.append({"role": "system", "content": _flatten_content(system)})
        for message in messages:
            role, content = message["role"], message["content"]
            if role not in ("user", "assistant"):
                raise ValueError("Anthropic messages require user or assistant roles")
            if isinstance(content, str):
                conversation.extend(_to_openai_messages([message], None))
                continue
            parts, calls, thinking, results = [], [], [], []
            # Tool responses precede the next user message on the predictor wire.
            # Extract their images first so the parallel image list follows that order.
            for block in sorted(content, key=lambda block: block["type"] != "tool_result"):
                match block["type"]:
                    case "text":
                        parts.append({"type": "text", "text": block["text"]})
                    case "image":
                        parts.append(self._image_part(block, images))
                    case "thinking" if role == "assistant":
                        thinking.append(block["thinking"])
                    case "tool_use" if role == "assistant":
                        calls.append({"id": block["id"], "type": "function", "function": {
                            "name": block["name"], "arguments": dumps(block["input"], separators=(",", ":"))
                        }})
                    case "tool_result" if role == "user":
                        result_content = block["content"]
                        if isinstance(result_content, list):
                            result_content = [
                                self._image_part(part, images) if part["type"] == "image" else part
                                for part in result_content
                            ]
                        if block.get("is_error"):
                            result_content = f"Error: {result_content}" if isinstance(result_content, str) else [
                                {"type": "text", "text": "Error:"}, *result_content
                            ]
                        results.append({"role": "tool", "tool_call_id": block["tool_use_id"], "content": result_content})
                    case _:
                        raise ValueError(f"Unsupported Anthropic content block: {block['type']}")
            conversation.extend(results)
            if parts or calls or thinking or not results:
                wire = {"role": role, "content": parts}
                if all(part["type"] == "text" for part in parts):
                    wire["content"] = _flatten_content(parts)
                if calls:
                    wire["tool_calls"] = calls
                if thinking:
                    wire["reasoning_content"] = "".join(thinking)
                conversation.append(wire)
        inputs = {self.messages.name: conversation}
        if images:
            inputs[self.images.name] = RemoteValue(dtype=Dtype.image_list, data=images)
        return inputs

    def _image_part(self, block: dict, images: list[RemoteValue]) -> dict:
        if self.images is None:
            raise ValueError("This predictor does not support image content")
        source = block["source"]
        if source["type"] == "base64":
            data = f"data:{source['media_type']};base64,{source['data']}"
        elif source["type"] == "url":
            data = source["url"]
        else:
            raise ValueError("Unsupported Anthropic image source")
        images.append(RemoteValue(dtype=Dtype.image, data=data))
        return {"type": "image"}


class ToolCallState(BaseModel):
    """
    Invocation-local buffering until a tool's header is available.
    """
    block: int | None = None
    id: str = ""
    name: str = ""
    arguments: list[str] = Field(default_factory=list)

def message_events(chunks: Iterable[ChatCompletionChunk]) -> Iterator[RawMessageStreamEvent]:
    """
    Translate chunk deltas into Anthropic block events without collecting text.
    Usage counters are predictor deltas; cache details are final snapshots.
    """
    started = False
    block_index = -1
    text_block = None
    text_kind = None
    tools: dict[int, ToolCallState] = {}
    input_tokens = output_tokens = 0
    cache_read = cache_write = None
    stop_reason = "end_turn"
    for chunk in chunks:
        if len(chunk.choices) > 1 or any(choice.index != 0 for choice in chunk.choices):
            raise ValueError("Anthropic messages require a single completion choice")
        if not started:
            started = True
            yield RawMessageStartEvent(message=Message(
                id=chunk.id,
                model=chunk.model,
                content=[],
                stop_reason=None,
                usage=Usage(input_tokens=0, output_tokens=0)
            ))
        if chunk.usage is not None:
            input_tokens += chunk.usage.prompt_tokens
            output_tokens += chunk.usage.completion_tokens
            details = chunk.usage.prompt_tokens_details
            if details is not None:
                if details.cached_tokens is not None:
                    cache_read = details.cached_tokens
                if details.cache_write_tokens is not None:
                    cache_write = details.cache_write_tokens
        if not chunk.choices:
            continue
        choice = chunk.choices[0]
        if choice.finish_reason is not None:
            stop_reason = _STOP_REASON_MAP[choice.finish_reason]
        if choice.delta is None:
            continue
        for kind, text in (
            ("thinking", choice.delta.reasoning_content),
            ("text", choice.delta.content)
        ):
            if not text:
                continue
            if text_kind != kind:
                if text_block is not None:
                    yield RawContentBlockStopEvent(index=text_block)
                block_index += 1
                text_block = block_index
                text_kind = kind
                yield RawContentBlockStartEvent(
                    index=text_block,
                    content_block=ThinkingBlock(thinking="") if kind == "thinking" else TextBlock(text="")
                )
            yield RawContentBlockDeltaEvent(
                index=text_block,
                delta=ThinkingDelta(thinking=text) if kind == "thinking" else TextDelta(text=text)
            )
        for call in choice.delta.tool_calls or []:
            if text_block is not None:
                yield RawContentBlockStopEvent(index=text_block)
                text_block = text_kind = None
            state = tools.setdefault(call.index, ToolCallState())
            if call.id:
                state.id += call.id
            if call.function is not None:
                if call.function.name:
                    state.name += call.function.name
                if call.function.arguments is not None:
                    state.arguments.append(call.function.arguments)
            if state.block is None and state.id and state.name:
                block_index += 1
                state.block = block_index
                yield RawContentBlockStartEvent(
                    index=state.block,
                    content_block=ToolUseBlock(id=state.id, name=state.name, input={})
                )
            if state.block is not None:
                for fragment in state.arguments:
                    if fragment:
                        yield RawContentBlockDeltaEvent(
                            index=state.block,
                            delta=InputJSONDelta(partial_json=fragment)
                        )
                state.arguments.clear()
    if not started:
        raise ValueError("Message predictor did not return any chunks")
    if text_block is not None:
        yield RawContentBlockStopEvent(index=text_block)
    for state in tools.values():
        if state.block is None:
            raise ValueError("Tool call did not provide an id and name")
        yield RawContentBlockStopEvent(index=state.block)
    yield RawMessageDeltaEvent(
        delta=RawMessageDeltaEvent.MessageDelta(stop_reason=stop_reason),
        usage=Usage(
            input_tokens=input_tokens - (cache_read or 0) - (cache_write or 0),
            output_tokens=output_tokens,
            cache_read_input_tokens=cache_read,
            cache_creation_input_tokens=cache_write
        )
    )
    yield RawMessageStopEvent()

def _to_openai_messages(
    messages: list[_MessageParamDict],
    system: str | list[_TextBlockParamDict] | None
) -> list[OpenAIMessage]:
    if not messages:
        raise ValueError("`messages` must contain at least one message.")
    result = list[OpenAIMessage]()
    if system is not None:
        result.append({ "role": "system", "content": _flatten_content(system) })
    for index, message in enumerate(messages):
        content = _flatten_content(message["content"])
        if message["role"] != "assistant" and not content.strip():
            raise ValueError(
                f"`messages[{index}]` ({message['role']} message) must have non-empty "
                "`content`. Text content must contain non-whitespace characters."
            )
        result.append({ "role": message["role"], "content": content })
    return result

def _flatten_content(content: str | list[_TextBlockParamDict]) -> str:
    if isinstance(content, str):
        return content
    if any(block["type"] != "text" for block in content):
        raise ValueError(
            "Failed to create message because only `text` content "
            "blocks are currently supported"
        )
    return "".join(block["text"] for block in content)

_STOP_REASON_MAP: dict[str, str] = {
    "stop": "end_turn",
    "length": "max_tokens",
    "content_filter": "refusal",
    "tool_calls": "tool_use"
}

