from __future__ import annotations
from base64 import b64encode
from io import BytesIO
from PIL import Image
from pydantic import BaseModel, ConfigDict, Field
from typing import Literal

from ...types import Dtype, Parameter, Prediction, RemoteValue, Signature, Value
from ._adapter import Adapter
from ._utils import (
    created, decode, get_parameter, inline_base64,
    result, validate_inputs, INTEGERS
)

class ImageData(BaseModel, **ConfigDict(arbitrary_types_allowed=True)):
    b64_json: str | None
    image: Image.Image | None

class ImageResponse(BaseModel):
    class Usage(BaseModel):
        class UsageInputTokensDetails(BaseModel):
            image_tokens: int = Field(description="The number of image tokens in the input prompt.")
            text_tokens: int = Field(description="The number of text tokens in the input prompt.")
        class UsageOutputTokensDetails(BaseModel):
            image_tokens: int = Field(description="The number of image output tokens generated by the model.")
            text_tokens: int = Field(description="The number of text output tokens generated by the model.")
        input_tokens: int = Field(description="The number of tokens (images and text) in the input prompt.")
        output_tokens: int = Field(description="The number of output tokens generated by the model.")
        total_tokens: int = Field(description="The total number of tokens (images and text) used for the image generation.")
        input_tokens_details: UsageInputTokensDetails = Field(description="The input tokens detailed information for the image generation.")
        output_tokens_details: UsageOutputTokensDetails | None = Field(default=None, description="The output token details for the image generation.")
    data: list[ImageData] | None = Field(description="The list of generated images.")
    background: Literal["transparent", "opaque"] | None = Field(description="The background parameter used for the image generation.")
    created: int = Field(description="The Unix timestamp (in seconds) of when the image was created.")
    usage: Usage | None = Field(default=None, description="the token usage information for the image generation.")

class OpenAIImageOptions(BaseModel, **ConfigDict(extra="forbid", frozen=True, strict=True)):
    """
    Image response encoding; ``raw`` returns Pillow images instead of base64.
    """
    format: Literal["png", "jpeg", "webp", "raw"] = "png"
    compression: int = Field(default=90, ge=0, le=100)

class OpenAIImageGenerationAdapter(Adapter[Prediction, OpenAIImageOptions, ImageResponse]):
    """
    Prepare text-to-image inputs and adapt native or encoded image outputs.
    """
    kind: Literal["openai.images.generate"] = "openai.images.generate"
    prompt: Parameter
    output: int
    count: Parameter | None = None
    width: Parameter | None = None
    height: Parameter | None = None

    @classmethod
    def from_signature(cls, signature: Signature) -> OpenAIImageGenerationAdapter:
        """
        Create an OpenAI image generation adapter from a predictor signature.
        """
        signature = signature.model_copy(deep=True)
        # Prompt parameter
        _, prompt = get_parameter(
            signature.inputs,
            dtype=Dtype.string,
            denotation="openai.images.prompt"
        )
        if prompt is None:
            raise ValueError("Requires one scalar string input annotated with ImagePrompt")
        # Optional generation width
        _, width = get_parameter(
            signature.inputs,
            dtype=INTEGERS,
            denotation="openai.images.width"
        )
        if width is not None and not width.optional:
            raise ValueError("Image generation `width` input must be optional")
        # Optional generation height
        _, height = get_parameter(
            signature.inputs,
            dtype=INTEGERS,
            denotation="openai.images.height"
        )
        if height is not None and not height.optional:
            raise ValueError("Image generation `height` input must be optional")
        # Optional generation count
        _, count = get_parameter(
            signature.inputs,
            dtype=INTEGERS,
            denotation="openai.images.count"
        )
        if count is not None and not count.optional:
            raise ValueError("Image generation `count` input must be optional")
        # Validate inputs
        validate_inputs(signature, [prompt, width, height, count])
        # Image output
        outputs = [
            idx
            for idx, param in enumerate(signature.outputs)
            if param.dtype == Dtype.image_list
        ]
        if len(outputs) != 1:
            raise ValueError("Requires one unambiguous image_list output")
        output = outputs[0]
        # Return
        return cls(
            prompt=prompt,
            output=output,
            count=count,
            width=width,
            height=height
        )

    def inputs(
        self,
        *,
        prompt: str,
        n: int | None = None,
        width: int | None = None,
        height: int | None = None
    ) -> dict[str, Value]:
        """
        Create prediction inputs from an image generation request.
        """
        inputs = { self.prompt.name: prompt }
        if self.count is not None and n is not None:
            inputs[self.count.name] = n
        if self.width is not None and width is not None:
            inputs[self.width.name] = width
        if self.height is not None and height is not None:
            inputs[self.height.name] = height
        return inputs

    def adapt(
        self,
        prediction: Prediction,
        options: OpenAIImageOptions | None = None
    ) -> ImageResponse:
        """
        Adapt a prediction to an OpenAI image generation response.
        """
        return _image_response(prediction, self.output, options)

def _image_response(
    prediction: Prediction,
    output: int,
    options: OpenAIImageOptions | None = None
) -> ImageResponse:
    options = options or OpenAIImageOptions()
    images = result(prediction, output)
    if isinstance(images, RemoteValue):
        if images.dtype != Dtype.image_list:
            raise ValueError("Expected an image_list output")
        images = images.data if isinstance(images.data, list) else decode(images, Dtype.image_list)
    if not isinstance(images, list) or not images:
        raise ValueError("Image predictor must return a nonempty image list")
    return ImageResponse(
        created=created(prediction), background=None,
        data=[_image_data(image, options) for image in images]
    )

def _image_data(
    value: object,
    options: OpenAIImageOptions
) -> ImageData:
    if isinstance(value, RemoteValue) and value.dtype != Dtype.image:
        raise ValueError("Each image result must have dtype image")
    recompress = options.format in ("jpeg", "webp") and "compression" in options.model_fields_set
    if isinstance(value, RemoteValue) and options.format != "raw" and not recompress:
        payload = inline_base64(value, {f"image/{options.format}"})
        if payload is not None:
            return ImageData(b64_json=payload, image=None)
    image = decode(value, Dtype.image)
    if not isinstance(image, Image.Image):
        raise ValueError("Each image result must be a Pillow image or RemoteValue image")
    if options.format == "raw":
        return ImageData(image=image, b64_json=None)
    buffer = BytesIO()
    if options.format == "jpeg":
        image = image.convert("RGB")
    kwargs = {"quality": options.compression} if options.format in ("jpeg", "webp") else {}
    image.save(buffer, format=options.format.upper(), **kwargs)
    return ImageData(image=None, b64_json=b64encode(buffer.getvalue()).decode())
