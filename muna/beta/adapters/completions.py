class Message(TypedDict):
    """
    Chat message.

    A plain dict so compiled chat predictors pass the conversation straight to the
    tokenizer's chat template, which normalizes content parts itself. Optional fields
    are omitted when absent.
    """
    role: Literal["assistant", "user", "system", "developer", "tool"]
    content: str | list[ChatCompletionContentPart] | None
    reasoning_content: NotRequired[str | None]
    tool_calls: NotRequired[list[ChatCompletionMessageFunctionToolCall] | None]
    tool_call_id: NotRequired[str | None]

class DeltaMessage(BaseModel):
    role: Literal["assistant", "user", "system", "tool"] | None = None
    content: str | None = None
    reasoning_content: str | None = Field(None, description="Reasoning contents of the message delta, before the final answer. Follows the DeepSeek convention for reasoning models.")
    tool_calls: list[ChoiceDeltaToolCall] | None = Field(None, description="Streamed tool call fragments, accumulated by `index`.")

class OpenAICompletionsOptions(BaseModel, **ConfigDict(extra="forbid", frozen=True, strict=True)):
    """
    Response options. Usage is emitted as a final, usage-only chunk.
    """
    include_usage: bool = False

class OpenAICompletionsAdapter(Adapter[Iterable[Prediction], OpenAICompletionsOptions, Iterator[ChatCompletionChunk]]):
    """
    Prepare chat inputs and lazily adapt a prediction stream into chunks.
    """
    kind: Literal["openai.chat.completions.create"] = Field("openai.chat.completions.create", init=False)
    messages: Parameter
    output: int
    images: Parameter | None = None
    audios: Parameter | None = None
    temperature: Parameter | None = None
    top_p: Parameter | None = None
    seed: Parameter | None = None
    max_completion_tokens: Parameter | None = None
    frequency_penalty: Parameter | None = None
    presence_penalty: Parameter | None = None
    response_format: Parameter | None = None
    reasoning_effort: Parameter | None = None
    tools: Parameter | None = None
    stop: Parameter | None = None

    @classmethod
    def from_signature(cls, signature: Signature) -> OpenAICompletionsAdapter | None:
        """
        Create an OpenAI chat completions adapter from a predictor signature.
        """
        signature = signature.model_copy(deep=True)
        # Messages parameter
        _, messages = get_parameter(
            [p for p in signature.inputs if not p.optional],
            dtype=Dtype.list,
            denotation="openai.chat.completions.messages"
        )
        if messages is None:
            return None
        # Images parameter
        _, images = get_parameter(
            signature.inputs,
            dtype=Dtype.image_list,
            denotation="openai.chat.completions.images"
        )
        # Audios parameter
        _, audios = get_parameter(
            signature.inputs,
            dtype=Dtype.array_list,
            denotation="openai.chat.completions.audios"
        )
        # Temperature
        _, temperature = get_parameter(
            signature.inputs,
            dtype=FLOATS,
            denotation="openai.chat.completions.temperature"
        )
        # Top P
        _, top_p = get_parameter(
            signature.inputs,
            dtype=FLOATS,
            denotation="openai.chat.completions.top_p"
        )
        # Seed
        _, seed = get_parameter(
            signature.inputs,
            dtype=INTEGERS,
            denotation="openai.chat.completions.seed"
        )
        # Maximum completion tokens
        _, max_completion_tokens = get_parameter(
            signature.inputs,
            dtype=INTEGERS,
            denotation="openai.chat.completions.max_output_tokens"
        )
        # Frequency penalty
        _, frequency_penalty = get_parameter(
            signature.inputs,
            dtype=FLOATS,
            denotation="openai.chat.completions.frequency_penalty"
        )
        # Presence penalty
        _, presence_penalty = get_parameter(
            signature.inputs,
            dtype=FLOATS,
            denotation="openai.chat.completions.presence_penalty"
        )
        # Response format
        _, response_format = get_parameter(
            signature.inputs,
            dtype=Dtype.dict,
            denotation="openai.chat.completions.response_format"
        )
        # Reasoning effort
        _, reasoning_effort = get_parameter(
            signature.inputs,
            dtype=Dtype.string,
            denotation="openai.chat.completions.reasoning_effort"
        )
        # Tools parameter
        _, tools = get_parameter(
            signature.inputs,
            dtype=Dtype.list,
            denotation="openai.chat.completions.tools"
        )
        # Stop sequences
        _, stop = get_parameter(
            signature.inputs,
            dtype=Dtype.list,
            denotation="openai.chat.completions.stop"
        )
        # Validate inputs
        if not validate_inputs(signature, [
            messages,
            images,
            audios,
            temperature,
            top_p,
            seed,
            max_completion_tokens,
            frequency_penalty,
            presence_penalty,
            response_format,
            reasoning_effort,
            tools,
            stop
        ]):
            return None
        # Check audios
        if audios is not None and audios.sample_rate is None:
            return None
        # Get completion chunk output
        outputs = [
            i
            for i, p in enumerate(signature.outputs)
            if p.dtype == Dtype.dict and (p.value_schema or {}).get("title") == "ChatCompletionChunk"
        ]
        if len(outputs) != 1:
            return None
        # Return
        return cls(
            messages=messages,
            output=outputs[0],
            images=images,
            audios=audios,
            temperature=temperature,
            top_p=top_p,
            seed=seed,
            max_completion_tokens=max_completion_tokens,
            frequency_penalty=frequency_penalty,
            presence_penalty=presence_penalty,
            response_format=response_format,
            reasoning_effort=reasoning_effort,
            tools=tools,
            stop=stop
        )

    def inputs(
        self,
        *,
        messages: list[Message],
        temperature: float | None = None,
        top_p: float | None = None,
        seed: int | None = None,
        max_completion_tokens: int | None = None,
        frequency_penalty: float | None = None,
        presence_penalty: float | None = None,
        response_format: dict | None = None,
        reasoning_effort: str | None = None,
        tools: list | None = None,
        stop: list[str] | None = None
    ) -> dict[str, Value]:
        """
        Create prediction inputs from a chat completions request.
        """
        inputs = self._conversation(messages)
        if self.temperature is not None and temperature is not None:
            inputs[self.temperature.name] = temperature
        if self.top_p is not None and top_p is not None:
            inputs[self.top_p.name] = top_p
        if self.seed is not None and seed is not None:
            inputs[self.seed.name] = seed
        if self.max_completion_tokens is not None and max_completion_tokens is not None:
            inputs[self.max_completion_tokens.name] = max_completion_tokens
        if self.frequency_penalty is not None and frequency_penalty is not None:
            inputs[self.frequency_penalty.name] = frequency_penalty
        if self.presence_penalty is not None and presence_penalty is not None:
            inputs[self.presence_penalty.name] = presence_penalty
        if self.response_format is not None and response_format is not None:
            inputs[self.response_format.name] = response_format
        if self.reasoning_effort is not None and reasoning_effort is not None:
            inputs[self.reasoning_effort.name] = reasoning_effort
        if self.tools is not None and tools is not None:
            if isinstance(tools, list):
                tools = [
                    tool.model_dump(exclude_none=True)
                    if isinstance(tool, BaseModel)
                    else tool
                    for tool in tools
                ]
            inputs[self.tools.name] = tools
        if self.stop is not None and stop is not None:
            inputs[self.stop.name] = stop
        return inputs

    def adapt(
        self,
        predictions: Iterable[Prediction],
        options: OpenAICompletionsOptions | None = None
    ) -> Iterator[ChatCompletionChunk]:
        """
        Yield chunks as predictions arrive; close the source on cancellation.
        """
        options = options or OpenAICompletionsOptions()
        source = iter(predictions)
        totals = [0, 0, 0]
        prompt_details = completion_details = None
        last = None
        has_usage = False
        try:
            for prediction in source:
                value = decode(result(prediction, self.output), Dtype.dict)
                chunk = ChatCompletionChunk.model_validate(value)
                last = chunk
                if chunk.usage is not None:
                    has_usage = True
                    usage = chunk.usage
                    totals = [
                        a + b
                        for a, b in zip(
                            totals,
                            (usage.prompt_tokens, usage.completion_tokens, usage.total_tokens)
                        )
                    ]
                    prompt_details = usage.prompt_tokens_details or prompt_details
                    completion_details = usage.completion_tokens_details or completion_details
                if chunk.choices:
                    yield chunk.model_copy(update={"usage": None}, deep=True)
            if last is None:
                raise ValueError("Chat predictor did not return any chunks")
            if options.include_usage and has_usage:
                yield last.model_copy(update={
                    "choices": [],
                    "usage": ChatCompletion.Usage(
                        prompt_tokens=totals[0],
                        completion_tokens=totals[1],
                        total_tokens=totals[2],
                        prompt_tokens_details=prompt_details,
                        completion_tokens_details=completion_details
                    )
                }, deep=True)
        finally:
            close = getattr(source, "close", None)
            if close is not None:
                close()

    def _conversation(self, messages: list[Message]) -> dict[str, Value]:
        if not messages:
            raise ValueError("messages must contain at least one message")
        normalized, images, audios = [], [], []
        for index, raw in enumerate(messages):
            message = _MESSAGE.validate_python(raw)
            _validate_message(index, message)
            wire = _MESSAGE.dump_python(message, mode="json", exclude_none=True)
            if message["role"] == "assistant" and message.get("content") is None:
                wire["content"] = ""
            content = message.get("content")
            for index, part in enumerate(content if isinstance(content, list) else []):
                if isinstance(part, ChatCompletionContentPartImage):
                    if self.images is None:
                        raise ValueError("This predictor does not support image content")
                    images.append(RemoteValue(dtype=Dtype.image, data=part.image_url.url))
                    wire["content"][index] = {"type": "image"}
                elif isinstance(part, ChatCompletionContentPartInputAudio):
                    parameter = self.audios
                    if parameter is None:
                        raise ValueError("This predictor does not support audio content")
                    audios.append(_decode_audio(part.input_audio, sample_rate=parameter.sample_rate))
                    wire["content"][index] = {"type": "audio"}
                elif isinstance(part, ChatCompletionContentPartFile):
                    raise ValueError("File content parts are not yet supported")
            normalized.append(wire)
        inputs = {self.messages.name: normalized}
        if not images and self.images is not None and not self.images.optional:
            raise ValueError("This predictor requires image content")
        if not audios and self.audios is not None and not self.audios.optional:
            raise ValueError("This predictor requires audio content")
        if images:
            inputs[self.images.name] = RemoteValue(dtype=Dtype.image_list, data=images)
        if audios:
            inputs[self.audios.name] = audios
        return inputs


def _validate_message(index: int, message: Message) -> None:
    """
    Reject a message that carries nothing for the model to read.
    """
    role = message["role"]
    if role in ("assistant", "tool"):
        return
    content = message.get("content")
    match content:
        case str():
            has_payload = bool(content.strip())
        case list():
            has_payload = any(
                part.text.strip() if isinstance(part, ChatCompletionContentPartText) else
                part.refusal.strip() if isinstance(part, ChatCompletionContentPartRefusal) else
                True
                for part in content
            )
        case _:
            has_payload = False
    if not has_payload:
        raise ValueError(
            f"`messages[{index}]` ({role} message) must have non-empty `content`. "
            "Text content must contain non-whitespace characters."
        )

def _decode_audio(
    input_audio: ChatCompletionContentPartInputAudio.InputAudio,
    *,
    sample_rate: int
) -> ndarray:
    """
    Decode an audio content part into linear PCM samples at the
    predictor's declared sample rate.
    """
    data = b64decode(input_audio.data)
    with NativeValue.from_bytes(data, f"audio/{input_audio.format};rate={sample_rate}") as value:
        return value.to_object()


_MESSAGE = TypeAdapter(Message)
